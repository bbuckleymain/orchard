const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("glass", {
  token: refresh => ipcRenderer.invoke("token", !!refresh),
  account: () => ipcRenderer.invoke("account"),
  signIn: () => ipcRenderer.invoke("sign-in"),
  signOut: () => ipcRenderer.invoke("sign-out"),
  lyrics: query => ipcRenderer.invoke("lyrics-external", query),
  musixmatchStatus: () => ipcRenderer.invoke("musixmatch-status"),
  setMusixmatchKey: key => ipcRenderer.invoke("musixmatch-key", key),
  lastfmStatus: () => ipcRenderer.invoke("lastfm-status"),
  setLastfmKey: key => ipcRenderer.invoke("lastfm-key", key),
  lastfmMatch: query => ipcRenderer.invoke("lastfm-match", query),
  lastfmAuth: () => ipcRenderer.invoke("lastfm-auth"),
  setLastfmSecret: value => ipcRenderer.invoke("lastfm-secret", value),
  lastfmConnect: () => ipcRenderer.invoke("lastfm-connect"),
  lastfmDisconnect: () => ipcRenderer.invoke("lastfm-disconnect"),
  lastfmRecommended: query => ipcRenderer.invoke("lastfm-recommended", query),
  lastfmSuggested: query => ipcRenderer.invoke("lastfm-suggested", query),
  window: action => ipcRenderer.send("window", action),
  mprisState: state => ipcRenderer.send("mpris-state", state),
  onMpris: cb => ipcRenderer.on("mpris", (_e, msg) => cb(msg)),
  localLibrary: () => ipcRenderer.invoke("local-library"),
  localAdd: kind => ipcRenderer.invoke("local-add", kind),
  localRescan: () => ipcRenderer.invoke("local-rescan"),
  localRemoveRoot: path => ipcRenderer.invoke("local-remove-root", path),
  localRemoveTrack: path => ipcRenderer.invoke("local-remove-track", path),
  localClear: () => ipcRenderer.invoke("local-clear"),
  localLyrics: path => ipcRenderer.invoke("local-lyrics", path),
  localReveal: path => ipcRenderer.invoke("local-reveal", path),
  localFetchLyrics: path => ipcRenderer.invoke("local-fetch-lyrics", path),
  localFetchLyricsMissing: () => ipcRenderer.invoke("local-fetch-lyrics-missing"),
  localFetchLyricsAll: () => ipcRenderer.invoke("local-fetch-lyrics-all"),
  artistPhoto: artist => ipcRenderer.invoke("artist-photo", artist),
  onLocalProgress: cb => ipcRenderer.on("local-progress", (_e, p) => cb(p)),
  onLyricsProgress: cb => ipcRenderer.on("local-lyrics-progress", (_e, p) => cb(p)),
});
